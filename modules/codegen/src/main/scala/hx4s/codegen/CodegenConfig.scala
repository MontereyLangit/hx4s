package hx4s.codegen

import java.nio.file.Path

/**
 * Settings for reading source files and generating HonoX wrappers.
 *
 * @param projectRoot Base directory for resolving relative source and generation paths.
 * @param serverSources Scala source paths scanned for `@route`.
 * @param clientSources Scala source paths scanned for `@islands`.
 * @param serverModule Required module ID of server-side `@JSExportTopLevel` declarations.
 * @param clientModule Compatibility setting validated as a module ID. Island imports use the IDs on their exports.
 * @param routeDir Route output directory.
 * @param islandDir Island output directory.
 * @param islandIdPrefix Prefix added to the island file path to form the HonoX hydration identifier.
 * @param scalaOutput Scala SSR API output file. Required by `Codegen.islandComponents`.
 * @param scalaPackage Package of the generated Scala SSR object.
 * @param scalaObject Name of the generated Scala SSR object.
 * @param islandBridge Fully qualified name used to call the island boundary constructor.
 * @param islandExportType Fully qualified name used to recognize typed client exports.
 * @param annotationPackage Package used to recognize qualified route and island annotations.
 * @param virtualModulePrefix Prefix prepended to Scala.js module filenames in imports.
 * @param banner Single-line `//` comments at the top of generated files. The first line must start with `generatedMarker`.
 * @param generatedMarker Prefix identifying generated files for replacement and cleanup.
 */
final case class CodegenConfig(
  projectRoot: Path,
  serverSources: List[String],
  clientSources: List[String],
  serverModule: String,
  clientModule: String,
  routeDir: String,
  islandDir: String,
  islandIdPrefix: String,
  scalaOutput: Option[Path],
  scalaPackage: String,
  scalaObject: String,
  islandBridge: String,
  islandExportType: String,
  annotationPackage: String,
  virtualModulePrefix: String,
  banner: List[String],
  generatedMarker: String
) {
  /** Resolves and normalizes the route output directory against `projectRoot`. */
  def routeRoot: Path = projectRoot.resolve(routeDir).normalize()
  /** Resolves and normalizes the island output directory against `projectRoot`. */
  def islandRoot: Path = projectRoot.resolve(islandDir).normalize()
  /** Builds an import specifier from a Scala.js module ID by adding the prefix and `.js` suffix. */
  def virtualModule(module: String): String = s"$virtualModulePrefix$module.js"
}

/** Provides the default settings and generated-file banner. */
object CodegenConfig {
  /** Default prefix used to recognize generated files. */
  val DefaultGeneratedMarker = "// This file is generated by hx4s-codegen"
  /** Default generated-file banner containing `DefaultGeneratedMarker`. */
  val DefaultBanner: List[String] = List(s"$DefaultGeneratedMarker. Do not edit this file manually.")

  /** Builds settings for the default HonoX layout and provided sources. Set `scalaOutput` before generating the Scala SSR API. */
  def default(projectRoot: Path, serverSources: List[String], clientSources: List[String]): CodegenConfig = CodegenConfig(
    projectRoot = projectRoot,
    serverSources = serverSources,
    clientSources = clientSources,
    serverModule = "server",
    clientModule = "client",
    routeDir = "app/routes",
    islandDir = "app/islands",
    islandIdPrefix = "/app/islands/",
    scalaOutput = None,
    scalaPackage = "hx4s.generated",
    scalaObject = "IslandComponents",
    islandBridge = "hx4s.react.Island",
    islandExportType = "hx4s.react.IslandExport",
    annotationPackage = "hx4s.annotation",
    virtualModulePrefix = "scalajs:",
    banner = DefaultBanner,
    generatedMarker = DefaultGeneratedMarker
  )
}
