package hx4s.codegen

import java.nio.file.Path

/**
 * Codegen settings. Relative paths are resolved from projectRoot
 * @param serverSources       source files searched for `@route`
 * @param clientSources       source files searched for `@islands`
 * @param serverModule        moduleID of server-side `@JSExportTopLevel`
 * @param clientModule        legacy client module setting kept for compatibility. Island module IDs come from their exports
 * @param routeDir            output directory for route files
 * @param islandDir           output directory for island files
 * @param islandIdPrefix      prefix of the island identifier passed to HonoX during SSR
 * @param scalaOutput         output file of the Scala API for SSR. Not written if None
 * @param scalaPackage        package name of the Scala API for SSR
 * @param scalaObject         object name of the Scala API for SSR
 * @param islandBridge        fully qualified name of the function that marks island hydration boundaries
 * @param islandExportType    fully qualified name of the type matched against @islands[P] as the declared type of client exports
 * @param annotationPackage   package of the `route` / `islands` annotations
 * @param virtualModulePrefix prefix of the virtual module pointing to the Scala.js link output
 * @param banner              first lines of generated files. The first line starts with generatedMarker
 * @param generatedMarker     prefix of the first line that identifies generated files
 */
final case class CodegenConfig(
  projectRoot: Path,
  serverSources: List[String],
  clientSources: List[String],
  serverModule: String,
  clientModule: String,
  routeDir: String,
  islandDir: String,
  islandIdPrefix: String,
  scalaOutput: Option[Path],
  scalaPackage: String,
  scalaObject: String,
  islandBridge: String,
  islandExportType: String,
  annotationPackage: String,
  virtualModulePrefix: String,
  banner: List[String],
  generatedMarker: String
) {
  def routeRoot: Path = projectRoot.resolve(routeDir).normalize()
  def islandRoot: Path = projectRoot.resolve(islandDir).normalize()
  def virtualModule(module: String): String = s"$virtualModulePrefix$module.js"
}

object CodegenConfig {
  val DefaultGeneratedMarker = "// This file is generated by hx4s-codegen"
  val DefaultBanner: List[String] = List(s"$DefaultGeneratedMarker. Do not edit this file manually.")

  /** Settings using HonoX's default layout (app/routes, app/islands), the server / client moduleIDs, the scalajs: virtual modules, and hx4s's annotations and bridge */
  def default(projectRoot: Path, serverSources: List[String], clientSources: List[String]): CodegenConfig = CodegenConfig(
    projectRoot = projectRoot,
    serverSources = serverSources,
    clientSources = clientSources,
    serverModule = "server",
    clientModule = "client",
    routeDir = "app/routes",
    islandDir = "app/islands",
    islandIdPrefix = "/app/islands/",
    scalaOutput = None,
    scalaPackage = "hx4s.generated",
    scalaObject = "IslandComponents",
    islandBridge = "hx4s.react.Island",
    islandExportType = "hx4s.react.IslandExport",
    annotationPackage = "hx4s.annotation",
    virtualModulePrefix = "scalajs:",
    banner = DefaultBanner,
    generatedMarker = DefaultGeneratedMarker
  )
}
